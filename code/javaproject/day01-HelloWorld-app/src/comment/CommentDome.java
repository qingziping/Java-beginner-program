package comment;

public class CommentDome {
    /**
     *
     * 这里是文档注释，main方法是程序的入口，如果没有main方法程序就不能执行
     *
     */
    public static void main(String[] args) {
        //单行注释，打印一行诗句
        System.out.println("明月几时有，把酒问青天");
        /*
        多行注释，打印多行诗句
         */
        System.out.println("莫听穿林打叶声，何妨吟啸且徐行");
        System.out.println("我欲乘风归去。又恐琼楼玉宇");
        System.out.println("天生我才必有用，千金散去还复来");
    }
}
